-- ── АЛХАМ 1: Хэдийг устгахыг шалгах (энд 700 гарах ёстой) ──
select count(*) as ustgah_too
from public.venues
where name like '% #%';


-- ── АЛХАМ 2: Үлдэх газруудыг харах (энд 12 жинхэнэ газар гарна) ──
select name, checkin_count
from public.venues
where name not like '% #%'
order by name;


-- ── АЛХАМ 3: Тоо таарч байвал УСТГАХ ──
--  Анхаар: venue_reviews дээрх 1 тест сэтгэгдэл хамт устана
--  (cascade). Тэр нь хоосон, 4 одтой тест бичлэг.
delete from public.venues
where name like '% #%';


-- ── АЛХАМ 4: Үр дүнг шалгах (нийт 12 үлдэх ёстой) ──
select count(*) as niit_uldsen from public.venues;
